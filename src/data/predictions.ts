export const PREDICTIONS: Prediction[] = TEXTS.map((text, i) => ({ id: i, text }))

/** Случайное предсказание, не совпадающее с предыдущим. */
export function pickPrediction(previousId: number | null): Prediction {
  let next: Prediction
  do {
    next = PREDICTIONS[Math.floor(Math.random() * PREDICTIONS.length)]!
  } while (PREDICTIONS.length > 1 && next.id === previousId)
  return next
}
